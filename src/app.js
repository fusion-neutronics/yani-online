/// script.js, imported the first time the Python tab is opened and never
/// before: it is what brings CodeMirror, Pyodide and the yani-core wheel, which
/// a visitor using only the form should not wait for or download. It sits
/// beside the page rather than inside it, so it needs the page served over
/// http(s); a page opened from a file says so instead.
let scriptMode = null;
function loadScriptMode() {
  if (!scriptMode) {
    scriptMode = import("./script.js").catch((e) => {
      scriptMode = null;
      throw e;
    });
  }
  return scriptMode;
}

function scriptUnavailable(text) {
  const note = $("script-unavailable");
  note.textContent = text;
  note.hidden = false;
}

/// Switch between the form and the Python tab. Answers the editor's module
/// once the Python tab is up, or null.
async function showMode(mode) {
  for (const b of document.querySelectorAll(".modes [data-mode]")) {
    b.setAttribute("aria-selected", String(b.dataset.mode === mode));
  }
  $("form-mode").hidden = mode !== "form";
  $("script-mode").hidden = true;
  $("script-unavailable").hidden = true;
  if (mode !== "python") return null;
  if (!/^https?:$/.test(location.protocol)) {
    scriptUnavailable(
      "The Python tab runs on Pyodide, which a page opened from a file cannot start. " +
      "It works on https://fusion-neutronics.github.io/yani-online/, or on a copy served over http.");
    return null;
  }
  $("script-mode").hidden = false;
  try {
    return await loadScriptMode();
  } catch (e) {
    $("script-mode").hidden = true;
    scriptUnavailable(`The Python tab could not load: ${e.message || e}`);
    return null;
  }
}

function wireModes() {
  for (const b of document.querySelectorAll(".modes [data-mode]")) {
    b.addEventListener("click", () => showMode(b.dataset.mode));
  }
  // The form's setup, as a script, in the editor. The same script the
  // download writes, except that it draws its figures in the page.
  $("open-python").addEventListener("click", async () => {
    try {
      warn("");
      const text = pythonScript(await currentSetup(), { browser: true });
      const editor = await showMode("python");
      if (editor) editor.openCode(text);
    } catch (e) {
      warn(`Cannot write the script: ${e.message || e}`);
    }
  });
  // A share link carries its code in the hash, and opens on the editor.
  if (new URLSearchParams(location.hash.slice(1)).has("code")) showMode("python");
}

// --- wiring ---------------------------------------------------------------

function wireTabs() {
  // The form's own tab strips. The Form/Python switch and the Python tab's
  // strip are not in a panel and are wired where they live.
  for (const tablist of document.querySelectorAll('.panel [role="tablist"]')) {
    tablist.addEventListener("click", (e) => {
      const btn = e.target.closest('[role="tab"]');
      if (!btn) return;
      const panel = tablist.closest(".panel");
      for (const t of tablist.querySelectorAll('[role="tab"]')) {
        t.setAttribute("aria-selected", String(t === btn));
      }
      for (const body of panel.querySelectorAll("[data-panel]")) {
        body.hidden = body.dataset.panel !== btn.dataset.tab;
      }
      refreshBudget();
      refreshSpectrum();
    });
  }
}

/// Offer every preset, in the order src/spectra.js lists them: the first is the
/// default, which is the first-wall spectrum of the HCPB blanket.
function wireSpectrumPresets() {
  const select = $("spectrum-preset");
  select.innerHTML = "";
  for (const [key, preset] of Object.entries(SPECTRA)) {
    const option = document.createElement("option");
    option.value = key;
    option.textContent = preset.label;
    option.title = preset.description;
    select.append(option);
  }
}

function wireDataDropdowns() {
  const fields = [
    ["data-xs", "xs"],
    ["data-reactions", "reactions"],
    ["data-decay", "decay"],
    ["data-fpy", "fission_yields"],
    ["data-branching", "branching"],
  ];
  for (const [id, subsection] of fields) {
    const select = $(id);
    select.innerHTML = "";
    for (const [name, publishes] of Object.entries(LIBRARIES)) {
      if (!publishes[subsection]) continue;
      const option = document.createElement("option");
      option.value = name;
      option.textContent = name;
      option.selected = name === DEFAULTS[subsection];
      select.append(option);
    }
  }
}

function renderComposition() {
  const body = $("composition");
  body.innerHTML = "";
  state.composition.forEach((row, i) => {
    const tr = document.createElement("tr");
    tr.innerHTML =
      `<td><input value="${row.name}" data-i="${i}" data-k="name"
                  placeholder="Fe, Li6, H2O"></td>` +
      `<td class="num"><input type="number" step="any" value="${row.fraction}"
                  data-i="${i}" data-k="fraction"></td>` +
      `<td><button class="secondary" data-remove="${i}">&times;</button></td>`;
    body.append(tr);
  });
}

/// A flux for the schedule table: "1e14" rather than the fifteen digits a
/// number input would show of it, of which the cell has room for eight. So the
/// rate is a text input, in the exponent form Python and JavaScript both read,
/// and anything under a hundred thousand stays plain.
function formatRate(rate) {
  if (!Number.isFinite(rate)) return "";
  if (Math.abs(rate) < 1e5) return String(rate);
  const [mantissa, exponent] = rate.toExponential(3).split("e");
  return `${Number(mantissa)}e${Number(exponent)}`;
}

function renderSchedule() {
  const body = $("schedule");
  body.innerHTML = "";
  state.schedule.forEach((step, i) => {
    const units = ["s", "min", "h", "d", "a"]
      .map((u) => `<option value="${u}"${u === step.unit ? " selected" : ""}>${u}</option>`)
      .join("");
    const tr = document.createElement("tr");
    tr.innerHTML =
      `<td>${step.kind === "pulse" ? "Pulse" : "Cooldown"}</td>` +
      `<td class="num">${
        step.kind === "pulse"
          ? `<input type="text" inputmode="decimal" value="${formatRate(step.rate)}" data-s="${i}" data-k="rate">`
          : "--"
      }</td>` +
      `<td class="num"><div class="inline">` +
      `<input type="number" step="any" value="${step.value}" data-s="${i}" data-k="value">` +
      `<select data-s="${i}" data-k="unit">${units}</select></div></td>` +
      `<td><button class="secondary" data-remove-step="${i}">&times;</button></td>`;
    body.append(tr);
  });
}

async function main() {
  wireTabs();
  wireModes();
  wireSpectrumPresets();
  wireDataDropdowns();
  renderComposition();
  renderSchedule();

  setStatus("Starting the solver…");
  await bootPlotly();
  state.solver = await bootSolver();
  state.caps = await state.solver.capabilities();
  setStatus("Ready. Choose a material, then download the data it needs.");

  // The compendium is compiled into the wasm, so the picker works before a
  // single byte is fetched.
  const names = await state.solver.pnnlNames();
  const fill = (list) => {
    const select = $("pnnl-select");
    select.innerHTML = "";
    for (const name of list.slice(0, 400)) {
      const option = document.createElement("option");
      option.value = option.textContent = name;
      select.append(option);
    }
  };
  fill(names);
  // Searching is a round trip now, so a fast typist can outrun the answers.
  // Only the newest is drawn, for the same reason the budget drops stale ones.
  let searchToken = 0;
  $("pnnl-search").addEventListener("input", async (e) => {
    const q = e.target.value.trim();
    const token = ++searchToken;
    const list = q ? await state.solver.pnnlSearch(q) : names;
    if (token === searchToken) fill(list);
  });
  $("pnnl-select").addEventListener("change", refreshBudget);
  $("volume").addEventListener("change", refreshBudget);
  // The library and the temperature decide what is fetched, so a change of
  // either turns "all held" back into a download, and a chain library turns it
  // into a fresh session.
  for (const id of ["data-xs", "data-reactions", "data-decay", "data-fpy", "data-branching", "temperature"]) {
    $(id).addEventListener("change", refreshBudget);
  }

  // Every control that changes the spectrum redraws it. `input` rather than
  // `change` on the pasted vector so the plot follows the typing.
  $("spectrum-preset").addEventListener("change", refreshSpectrum);
  $("group-structure").addEventListener("change", refreshSpectrum);
  $("group-flux").addEventListener("input", refreshSpectrum);
  refreshSpectrum();
  // And the material, which on the compendium tab with nothing picked yet says
  // so rather than drawing nothing silently.
  refreshBudget();

  $("composition").addEventListener("input", (e) => {
    const { i, k } = e.target.dataset;
    if (i === undefined) return;
    state.composition[i][k] = k === "fraction" ? Number(e.target.value) : e.target.value;
    refreshBudget();
  });
  $("composition").addEventListener("click", (e) => {
    const i = e.target.dataset.remove;
    if (i === undefined) return;
    state.composition.splice(Number(i), 1);
    renderComposition();
  });
  $("add-component").addEventListener("click", () => {
    state.composition.push({ name: "", fraction: 1.0 });
    renderComposition();
  });

  $("schedule").addEventListener("input", (e) => {
    const { s, k } = e.target.dataset;
    if (s === undefined) return;
    if (k === "unit") {
      state.schedule[s][k] = e.target.value;
      return;
    }
    // The rate is free text, so it can fail to be a number in a way a number
    // input cannot. A half-typed "2e" is marked and the last good value kept,
    // rather than a NaN reaching the solver as a step with no rate.
    const value = Number(e.target.value.trim());
    const valid = e.target.value.trim() !== "" && Number.isFinite(value) && value >= 0;
    e.target.classList.toggle("invalid", !valid);
    if (valid) state.schedule[s][k] = value;
  });
  $("schedule").addEventListener("click", (e) => {
    const i = e.target.dataset.removeStep;
    if (i === undefined) return;
    state.schedule.splice(Number(i), 1);
    renderSchedule();
  });
  $("add-pulse").addEventListener("click", () => {
    state.schedule.push({ kind: "pulse", rate: 1e14, value: 1, unit: "h" });
    renderSchedule();
  });
  $("add-cooldown").addEventListener("click", () => {
    state.schedule.push({ kind: "cooldown", value: 1, unit: "d" });
    renderSchedule();
  });

  $("run").addEventListener("click", run);
  $("export").addEventListener("click", async () => {
    try {
      warn("");
      if (!state.results) throw new Error("run first: the export carries this run's results");
      const setup = await currentSetup();
      const saved = new Date();
      const stamp = saved.toISOString().slice(0, 19).replace(/[:T]/g, "-");
      downloadFile(
        `yani_session_${stamp}.html`,
        await sessionDocument({ saved: saved.toISOString(), setup, results: state.results }),
        "text/html");
    } catch (e) {
      warn(`Cannot export the session: ${e.message || e}`);
    }
  });
  $("download-python").addEventListener("click", async () => {
    try {
      warn("");
      downloadFile("yani_run.py", pythonScript(await currentSetup()), "text/x-python");
    } catch (e) {
      warn(`Cannot write the script: ${e.message || e}`);
    }
  });
  // A scale toggle redraws only the chart it belongs to. The spectrum is drawn
  // from the form, the rest from the last results, so there is nothing to
  // redraw for those until a run has happened.
  wireAxisScales((id) => {
    if (id === "plot-spectrum") {
      refreshSpectrum();
    } else if (state.results) {
      if (id === "plot-photons") drawPhotons(state.results, Number($("photon-step").value));
      else if (id === "plot-inventory") drawInventory(state.results, Number($("inventory-step").value));
      else drawAll(state.results);
    }
  });

  // The palettes are separately validated per theme rather than flipped, so a
  // theme change rebuilds the charts. The spectrum is up before any run, which
  // is exactly when someone is most likely to switch.
  window.addEventListener("yani:redraw", () => {
    refreshSpectrum();
    drawMaterial(state.material);
    if (state.results) {
      drawAll(state.results);
      drawInventory(state.results, Number($("inventory-step").value));
      drawPhotons(state.results, Number($("photon-step").value));
    }
  });

  // The stepped charts each have a slider of their own: the inventory and the
  // photon lines are looked at for different reasons, and a reader comparing
  // the inventory at two steps should not have the photon plot jumping about
  // under it.
  $("inventory-step").addEventListener("input", (e) => {
    const i = Number(e.target.value);
    $("inventory-step-label").value = i + 1;
    if (state.results) drawInventory(state.results, i);
  });
  $("photon-step").addEventListener("input", (e) => {
    const i = Number(e.target.value);
    $("photon-step-label").value = i + 1;
    if (state.results) drawPhotons(state.results, i);
  });

  // A file exported from this page carries its session; put it back, last, so
  // that every control it drives is wired. Nothing is fetched for it.
  const saved = document.getElementById("yani-session");
  if (saved) {
    try {
      await restoreSession(JSON.parse(await gunzipB64(saved.textContent.trim())));
    } catch (e) {
      warn(`This file carries a saved session that could not be restored: ${e.message || e}`);
    }
  }
}

main().catch((e) => {
  warn(`Failed to start: ${e.message || e}`);
});
